"""Bitmap font for Trawler, from a BDF file (the firmware stores no hand-written glyphs).

    python3 tools/gen_font.py assets/fonts/ter-u12n.bdf build/gen/font.h

Python 3.9+, standard library only, deterministic output. Provisional (P0-04): one monospace
face, ASCII 32..126, one byte per row with bit 7 the leftmost pixel, so FONT_W <= 8. P1-04
extends it (the 6x10 or 8x12 choice, Q-02). The default font is Terminus 12 (6x12, Dimitar
Toshkov Zhekov, SIL OFL 1.1, assets/fonts/Terminus-LICENSE.txt); the generated data stays OFL.
"""
import sys
from pathlib import Path

FIRST, LAST = 32, 126


def parse(path):
    """(width, height, {code: [row bits, top to bottom]}) of a monospace BDF font"""
    box, glyphs, cur, rows = None, {}, None, None
    for line in Path(path).read_text(encoding="latin-1").splitlines():
        f = line.split()
        if not f:
            continue
        if f[0] == "FONTBOUNDINGBOX":
            box = tuple(int(v) for v in f[1:5])
        elif f[0] == "ENCODING":
            cur = int(f[1])
        elif f[0] == "BBX":
            assert box and tuple(int(v) for v in f[1:5]) == box, f"glyph {cur}: BBX {f[1:5]} != {box}"
        elif f[0] == "BITMAP":
            rows = []
        elif f[0] == "ENDCHAR":
            if FIRST <= cur <= LAST:
                assert len(rows) == box[1], f"glyph {cur}: {len(rows)} rows"
                glyphs[cur] = rows
            cur, rows = None, None
        elif rows is not None:
            assert len(f[0]) == 2, f"glyph {cur}: row {f[0]}"
            rows.append(int(f[0], 16))
    assert box, "no FONTBOUNDINGBOX"
    w, h = box[0], box[1]
    assert w <= 8, f"width {w}: one byte per row"
    missing = [c for c in range(FIRST, LAST + 1) if c not in glyphs]
    assert not missing, f"missing glyphs {missing}"
    return w, h, glyphs


def main(src, dst):
    w, h, glyphs = parse(src)
    name = "FONT_%dX%d" % (w, h)
    L = ["/* SPDX-License-Identifier: OFL-1.1 */",
         "/* generated by tools/gen_font.py from %s: do not edit */" % Path(src).name,
         "/* Terminus font, Copyright (C) 2020 Dimitar Toshkov Zhekov, SIL Open Font License 1.1 */",
         "#pragma once",
         "#include <stdint.h>",
         "",
         "#define FONT_W %d" % w,
         "#define FONT_H %d" % h,
         "#define FONT_FIRST %d" % FIRST,
         "#define FONT_LAST %d" % LAST,
         "#define FONT %s" % name,
         "",
         "/* one row per byte, top to bottom, bit 7 = leftmost pixel */",
         "static const uint8_t %s[%d][%d] = {" % (name, LAST - FIRST + 1, h)]
    for c in range(FIRST, LAST + 1):
        L.append("    {%s}, /* %s */" % (", ".join("0x%02X" % r for r in glyphs[c]), chr(c)))
    L.append("};")
    Path(dst).parent.mkdir(parents=True, exist_ok=True)
    Path(dst).write_text("\n".join(L) + "\n")


if __name__ == "__main__":
    if len(sys.argv) != 3:
        sys.exit(__doc__)
    main(sys.argv[1], sys.argv[2])
