"""Fixed-point lookup tables for Trawler (the firmware has no float and no libm).

    python3 tools/gen_tables.py build/gen/tables.h

Python 3.9+, deterministic output. The pitch table uses Felucca's method (tools/gen_tables.py,
Copyright (C) 2026 Leo Kuroshita, Hugelton Instruments, GPL-3.0-only): only the top octave is
stored, lower octaves are the same values shifted right, which is bit-exact (checked below).
"""
import math
import sys
from pathlib import Path

FS = 44100           # nominal device rate (the real I2S rate is 44117.6 Hz, Q-11)
SINE_N = 1024        # sine table points (plus one guard point: no wrap for interpolation)
FINE = 16            # pitch steps per semitone
A4 = 57              # note number of A-4 = 440 Hz (0 = C-0, 119 = B-9; note = MIDI - 12)
PITCH_N = 2048       # pitch domain: 0..2047 in 1/16 semitone (notes 0..127)
OCT = 12 * FINE      # 192 entries per octave
TOP = PITCH_N - OCT  # first pitch of the stored (top) octave: 1856
OFS = 64             # (p + OFS) // 192 is the octave block, 10 for the top octave
BLK_TOP = (TOP + OFS) // OCT


def arr(name, ctype, vals, per=12):
    out = ["static const %s %s[%d] = {" % (ctype, name, len(vals))]
    for i in range(0, len(vals), per):
        out.append("    " + ", ".join(str(v) for v in vals[i:i + per]) + ",")
    out.append("};")
    return out


def pitch_inc_exact(p):
    """Phase increment of pitch p (1/16 semitone) for a 32-bit phase at FS."""
    f = 440.0 * 2.0 ** ((p / FINE - A4) / 12.0)
    return int(f / FS * 2 ** 32)


def main(path):
    sine = [int(round(32767 * math.sin(2 * math.pi * i / SINE_N))) for i in range(SINE_N + 1)]

    full = [pitch_inc_exact(p) for p in range(PITCH_N)]
    assert all(0 < v < 2 ** 32 for v in full)
    top = full[TOP:]
    assert TOP + OFS == BLK_TOP * OCT
    # the compact table gives the full one, bit for bit, with the C lookup of dsp/fixed.h
    for p in range(PITCH_N):
        q = p + OFS
        blk = (q * 21846) >> 22
        assert blk == q // OCT
        assert full[p] == top[q - blk * OCT] >> (BLK_TOP - blk), p

    L = ["/* SPDX-License-Identifier: GPL-3.0-only */",
         "/* generated by tools/gen_tables.py: do not edit */",
         "#pragma once",
         "#include <stdint.h>",
         "",
         "#define FS %d" % FS,
         "#define SINE_BITS %d" % int(math.log2(SINE_N)),
         "#define PITCH_FINE %d" % FINE,
         "#define PITCH_MAX %d" % (PITCH_N - 1),
         "#define PITCH_OFS %d" % OFS,
         "#define PITCH_OCT_N %d" % OCT,
         "#define PITCH_BLK_TOP %d" % BLK_TOP,
         "#define NOTE_A4 %d" % A4,
         ""]
    L += arr("SINE_Q15", "int16_t", sine)
    L += [""]
    L += arr("PITCH_OCT", "uint32_t", top, 8)
    Path(path).parent.mkdir(parents=True, exist_ok=True)
    Path(path).write_text("\n".join(L) + "\n")


if __name__ == "__main__":
    main(sys.argv[1] if len(sys.argv) > 1 else "build/gen/tables.h")
